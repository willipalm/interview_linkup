HARD_WORKSHEET = "gold/hard_worksheet.csv"
LIST_COLS = ["required_facts", "acceptable_variants", "gold_sources", "authoritative_domains"]
MUST_FILL = ["answer_type", "gold_answer", "required_facts", "gold_sources", "as_of", "verified_by"]


def load_hard(path):
    """Rows from the human-researched worksheet. Only status=keep rows enter the gold set."""
    if not path.exists():
        return [], []
    keep, problems = [], []
    with open(path, newline="", encoding="utf-8") as f:
        for w in csv.DictReader(f):
            w = {k: (v or "").strip() for k, v in w.items()}
            if not w.get("as_of") and w.get("researched_on"):  # older worksheets named the column researched_on
                w["as_of"] = w["researched_on"]
            status = w["status"].lower()
            if status in {"todo", "drop", ""}:
                continue
            if status != "keep":
                problems.append(f"{w['id']}: status must be todo, keep or drop (got {w['status']!r})")
                continue
            missing = [c for c in MUST_FILL if not w[c]]
            if missing:
                problems.append(f"{w['id']}: status=keep but empty {missing}")
                continue
            r = {k: w[k] for k in FIELD_ORDER if k in w}
            for c in LIST_COLS:
                r[c] = [x.strip() for x in w[c].split("|") if x.strip()]
            r["hops"] = int(w["hops"])
            r["trap"] = w["trap"] or None
            r["workflow"] = w.get("workflow") or None
            # The worksheet carries every gold column. split, origin and expires_at are fixed or derived,
            # so a different value is an error rather than something to silently overwrite.
            for col, fixed in (("split", "test"), ("origin", "human")):
                if w.get(col) and w[col] != fixed:
                    problems.append(f"{w['id']}: {col} must be {fixed!r} for human-researched rows (got {w[col]!r})")
            r["split"], r["origin"] = "test", "human"
            r["point_in_time"] = w.get("point_in_time") or None
            r.pop("expires_at", None)  # computed from as_of + freshness in derive()
            notes = f"Why hard: {w['why_hard']}"
            r["verification_notes"] = f"{w['verification_notes']} [{notes}]" if w["verification_notes"] else f"[{notes}]"
            keep.append(r)
    return keep, problems


def derive(rows, twins=(), hard_rows=()):
    dev_ids = set(DEV_IDS) | {t["id"] for t in twins if t["parent"] in DEV_IDS}
    out = []
    for r in [*rows, *twins, *hard_rows]:
        r = dict(r)
        r.setdefault("as_of", AS_OF)
        r.setdefault("verified_by", "claude-research")
        r.setdefault("origin", "claude")
        r.setdefault("point_in_time", None)
        r.setdefault("workflow", None)
        days = EXPIRY_DAYS[r["freshness"]]
        as_of = dt.date.fromisoformat(r["as_of"])
        r["expires_at"] = (as_of + dt.timedelta(days=days)).isoformat() if days else None
        # human-researched hard rows always go to test: they exist to be reported, not tuned on
        r["split"] = "dev" if r["id"] in dev_ids else "test"
        out.append(r)
    return out


FIELD_ORDER = [
    "id", "split", "team", "sub_team", "persona_role", "pattern", "query", "intent_note",
    "answer_type", "gold_answer", "required_facts", "acceptable_variants", "gold_sources",
    "authoritative_domains", "as_of", "freshness", "expires_at", "hops", "difficulty", "trap",
    "verified_by", "verification_notes", "origin", "point_in_time", "workflow",
]


def main():
    root = pathlib.Path(__file__).resolve().parent.parent
    out_path = root / "gold" / "gold_set.jsonl"
    hard, problems = load_hard(root / HARD_WORKSHEET)
    for p in problems:
        print("WORKSHEET ERROR", p)
    if problems:
        return 1
    rows = derive(ROWS, PIT_TWINS, hard)
    with open(out_path, "w", encoding="utf-8") as f:
        for r in rows:
            f.write(json.dumps({k: r[k] for k in FIELD_ORDER}, ensure_ascii=False) + "\n")
    print(f"Wrote {len(rows)} rows to {out_path} ({len(ROWS)} claude-built + {len(PIT_TWINS)} point-in-time twins + {len(hard)} human-researched hard rows)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
